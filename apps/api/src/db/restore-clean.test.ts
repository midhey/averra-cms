import { readdirSync, readFileSync } from 'node:fs'
import { PGlite } from '@electric-sql/pglite'
import { afterEach, describe, expect, it } from 'vitest'

// Восстановление внешней базы (deploy/averra.sh, LOAD_DUMP_SCRIPT) перед загрузкой дампа удаляет
// схему drizzle и объекты public той же транзакцией. Подделка docker в тестах deploy этот SQL не
// выполняет — здесь он идёт на настоящей PostgreSQL (PGlite) после всех миграций Averra и с
// объектами, которых в миграциях пока нет: упади очистка на одном из них, каждое восстановление и
// откат внешней базы откатывались бы целиком

const script = readFileSync(new URL('../../../../deploy/averra.sh', import.meta.url), 'utf8')

/** SQL очистки — как он записан в averra.sh (heredoc averra-clean.sql) */
function cleanSql() {
  const match = /cat >\/tmp\/averra-clean\.sql <<'SQL'\n([\s\S]*?)\nSQL\n/.exec(script)
  if (!match?.[1]) throw new Error('в averra.sh нет SQL очистки')
  return match[1]
}

const folder = new URL('../../drizzle/', import.meta.url)

async function migrateAll(client: PGlite) {
  const files = readdirSync(folder)
    .filter((name) => name.endsWith('.sql'))
    .sort()
  for (const name of files) {
    const sql = readFileSync(new URL(name, folder), 'utf8')
    for (const statement of sql.split('--> statement-breakpoint')) await client.exec(statement)
  }
  // Таблица миграций, как её ведёт drizzle
  await client.exec(`
    CREATE SCHEMA drizzle;
    CREATE TABLE drizzle.__drizzle_migrations (id serial PRIMARY KEY, hash text NOT NULL);
    INSERT INTO drizzle.__drizzle_migrations (hash) VALUES ('a'), ('b');
  `)
  return files.length
}

/** Что осталось в public и есть ли схема drizzle */
async function leftovers(client: PGlite) {
  const { rows } = await client.query<{ kind: string; name: string }>(`
    SELECT 'rel' AS kind, c.relname AS name FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public'
    UNION ALL
    SELECT 'type', t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
      WHERE n.nspname = 'public' AND t.typtype IN ('e', 'd', 'r', 'c') AND t.typrelid = 0
    UNION ALL
    SELECT 'routine', p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
      WHERE n.nspname = 'public'
    UNION ALL
    SELECT 'schema', nspname FROM pg_namespace WHERE nspname = 'drizzle'
    ORDER BY 1, 2
  `)
  return rows
}

let client: PGlite | undefined
afterEach(async () => {
  await client?.close()
  client = undefined
})

describe('очистка базы перед загрузкой дампа (внешняя база)', () => {
  it('убирает все объекты после миграций Averra, IDENTITY и serial, а ROLLBACK их возвращает', async () => {
    client = new PGlite()
    const migrations = await migrateAll(client)
    expect(migrations).toBeGreaterThan(0)
    await client.exec(`
      CREATE TABLE identity_items (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name text);
      CREATE TABLE identity_default (id int GENERATED BY DEFAULT AS IDENTITY, note text);
      CREATE TABLE serial_items (id serial PRIMARY KEY, n bigserial);
      CREATE SEQUENCE free_counter;
      CREATE TYPE mood AS ENUM ('ok', 'bad');
      CREATE DOMAIN positive AS int CHECK (VALUE > 0);
      CREATE TYPE pair AS (a int, b text);
      CREATE VIEW identity_names AS SELECT name FROM identity_items;
      CREATE MATERIALIZED VIEW serial_count AS SELECT count(*) FROM serial_items;
      CREATE FUNCTION touch() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
      CREATE TRIGGER touch_items BEFORE INSERT ON identity_items FOR EACH ROW EXECUTE FUNCTION touch();
      CREATE PROCEDURE noop() LANGUAGE sql AS $$ SELECT 1 $$;
      CREATE TABLE parted (id int, at date) PARTITION BY RANGE (at);
      CREATE TABLE parted_2026 PARTITION OF parted FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
      INSERT INTO identity_items (name) VALUES ('Иван');
    `)
    const before = await leftovers(client)
    expect(before.length).toBeGreaterThan(20)

    await client.exec('BEGIN')
    await client.exec(cleanSql())
    expect(await leftovers(client)).toEqual([])
    await client.exec('ROLLBACK')

    expect(await leftovers(client)).toEqual(before)
    const { rows } = await client.query<{ name: string }>('SELECT name FROM identity_items')
    expect(rows).toEqual([{ name: 'Иван' }])
  })
})
