/**
 * Загрузка один раз на сборку. Снимок сайта читают несколько маршрутов: страницы, карточки
 * /og/*.png, sitemap, иконки. Каждый со своим запросом в API получил бы свою версию сайта, если
 * публикация пришлась на середину сборки: страница уже ссылается на /og/<адрес>.png, а маршрут
 * карточек этой страницы ещё не видел — в релизе ссылка на несуществующий файл. Один снимок на
 * сборку — релиз всегда согласован. В dev запоминать нельзя: там опубликованное видно сразу
 */
export function oncePerBuild<T>(load: () => Promise<T>, dev: boolean): () => Promise<T> {
  if (dev) return load
  let loaded: Promise<T> | undefined
  return () => {
    loaded ??= load()
    return loaded
  }
}
