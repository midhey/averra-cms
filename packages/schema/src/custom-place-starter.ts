/** Заготовка определения места: поле подписи, шаблон и CSS на переменных темы */
export function placeStarter(key: string, title: string, placement: 'header' | 'footer') {
  const header = placement === 'header'
  return {
    key,
    title,
    description: header
      ? 'Своя шапка сайта: логотип, меню и кнопка'
      : 'Свой подвал сайта: название, разделы и контакты',
    category: 'about',
    placement,
    fields: [
      header
        ? { type: 'text', name: 'tagline', label: 'Подпись под логотипом', maxLength: 60 }
        : { type: 'text', name: 'note', label: 'Подпись', maxLength: 120 },
    ],
    template: header ? headerTemplate : footerTemplate,
    css: header ? headerCss : footerCss,
    example: {},
  }
}
