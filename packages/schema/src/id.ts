import { z } from 'zod'

/**
 * Id записи (uuid) в одном написании — строчными буквами. z.uuid() принимает и заглавные,
 * Postgres сравнивает uuid без учёта регистра и отдаёт строчными. Без приведения один id
 * в двух написаниях расходится там, где сравниваются строки: ключи файлов, поиск ссылки
 * в JSON страницы, права токена на сайт
 */
export const Uuid = (message?: string) => z.uuid(message).toLowerCase()
