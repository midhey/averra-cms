// Адреса, которые уходят в HTML сайта и заголовок Location: путь на этом сайте и ссылка https. Одни
// правила у редиректов (раздел «SEO») и canonical страницы. Разбор шаблоном, а не URL: схема
// работает везде, где есть Zod, без API среды

/**
 * Домен: части из букв любого алфавита, цифр и дефиса (не по краям) через точку, зона начинается
 * с буквы. Кириллица — как есть (пример.рф): браузер сам переведёт её в punycode
 */
export const DOMAIN = String.raw`(?:[\p{L}\p{N}](?:[\p{L}\p{N}-]*[\p{L}\p{N}])?\.)+\p{L}[\p{L}\p{N}-]*[\p{L}\p{N}]`

/** https://домен и, может быть, косая черта — без порта, пути, параметров и логина */
export const HTTPS_ORIGIN = new RegExp(`^https://${DOMAIN}/?$`, 'iu')

/** Ссылка https:// на домен (без логина и пароля в адресе) и что угодно после него */
export const HTTPS_URL = new RegExp(String.raw`^https://${DOMAIN}(?::\d{1,5})?(?:[/?#]\S*)?$`, 'iu')

/**
 * Путь на этом сайте: / в начале, но не // и не /\. Браузер читает \ как /, и /\evil.example
 * увёл бы на чужой домен. Поэтому обратной косой черты и управляющих символов нет нигде в пути
 */
export const isInternalPath = (href: string) =>
  /^\/(?![/\\])/.test(href) && !/[\\\p{Cc}]/u.test(href)
